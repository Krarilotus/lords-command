// Spec (Sync, skills): a skill is installed as a link to the stack's dir, never a copy; a real dir in its place
// is backed up and replaced; dirs not from a stack are left alone; a link for a skill that no longer applies is
// removed without touching the stack.
#[test]
fn skills_are_links_into_the_stack() {
    let f = Fixture::new();
    skill(&f, "spec-tests", "---\nname: spec-tests\n---\nNew text.\n");
    skill(&f, "old", "---\nname: old\n---\nx\n");
    f.write("home/skills/spec-tests/SKILL.md", "---\nname: spec-tests\n---\nOld text.\n");
    f.write("home/skills/mine/SKILL.md", "mine\n");
    let dir = f.path("home/skills");
    with_targets(&f, &target("skills", "codex", "skills", &dir, ""));
    let opts = Options { user_only: true, ..Options::default() };
    let p = plan(&f.stacks(), &opts).unwrap();
    let by = |name: &str| p.items.iter().find(|i| i.path.ends_with(name)).unwrap();
    assert_eq!(by("old").action, Action::Link);
    assert_eq!(by("spec-tests").action, Action::ReplaceDir);
    assert!(by("spec-tests").diff.contains("-Old text.\n+New text."));
    assert!(p.items.iter().any(|i| i.notes.iter().any(|n| n.contains("left alone: mine"))));

    apply(&p, &f.path("backups")).unwrap();
    assert_eq!(
        f.read("home/skills/spec-tests/SKILL.md"),
        "---\nname: spec-tests\n---\nNew text.\n",
        "through the link"
    );
    assert!(fs::read_link(dir.join("spec-tests")).is_ok(), "a link, not a copy");
    assert_eq!(f.read("home/skills/mine/SKILL.md"), "mine\n");
    let backed: Vec<_> = fs::read_dir(f.path("backups")).unwrap().flatten().collect();
    assert_eq!(backed.len(), 1);
    assert!(plan(&f.stacks(), &opts).unwrap().items.iter().all(|i| i.action == Action::InSync));

    let side = f.read("pub/global/skills/old/lords.yaml");
    f.write(
        "pub/global/skills/old/lords.yaml",
        &side.replace(
            "status: active\n",
            "status: retired\nretired:\n  date: 2026-10-25\n  reason: gone\n",
        ),
    );
    let p = plan(&f.stacks(), &opts).unwrap();
    assert_eq!(p.items.iter().find(|i| i.path.ends_with("old")).unwrap().action, Action::Unlink);
    apply(&p, &f.path("backups2")).unwrap();
    assert!(!dir.join("old").exists());
    assert!(f.path("pub/global/skills/old/SKILL.md").exists(), "the stack keeps the skill");
}

// Spec (Sync, repo targets; docs/load-order.md): every checkout and worktree gets the untracked file each family
// reads (CLAUDE.local.md, AGENTS.override.md), listed once in the shared git exclude; a tracked file of that name
// is a conflict and nothing is applied; the tracked AGENTS.md is only reported, never written.
#[test]
fn repo_targets_write_untracked_files_in_every_worktree() {
    let f = Fixture::new();
    f.write(
        "priv/repo/beta-core/facts/h.md",
        &entry("fact.h", "repo:beta-core", "private", "", "Hosts through the fleet.\n"),
    );
    let main = f.path("checkout");
    f.write("checkout/AGENTS.md", "Tracked text.\n");
    f.git_init("checkout");
    git(&main, &["worktree", "add", "-q", "../wt", "-b", "wt"]);
    let manifest = format!(
        "name = \"priv\"\nvisibility = \"private\"\n[projects.beta]\n[repos.beta-core]\nproject = \"beta\"\ncheckouts = ['{}']\n",
        main.display()
    );
    f.write("priv/stack.toml", &manifest);
    let opts = Options { repo: Some("beta-core".into()), user_only: false };
    let p = plan(&f.stacks(), &opts).unwrap();
    let creates: Vec<String> = p
        .items
        .iter()
        .filter(|i| i.action == Action::Create && !i.target.contains("exclude"))
        .map(|i| {
            format!(
                "{}/{}",
                i.path.parent().unwrap().file_name().unwrap().to_string_lossy(),
                i.path.file_name().unwrap().to_string_lossy()
            )
        })
        .collect();
    assert_eq!(
        creates,
        [
            "checkout/CLAUDE.local.md",
            "wt/CLAUDE.local.md",
            "checkout/AGENTS.override.md",
            "wt/AGENTS.override.md"
        ]
    );
    let tracked = p.items.iter().find(|i| i.target.contains("tracked AGENTS.md")).unwrap();
    assert_eq!(
        tracked.action,
        Action::InSync,
        "no public entries apply, so the tracked file is as the stack would have it"
    );

    apply(&p, &f.path("backups")).unwrap();
    assert!(f.read("wt/AGENTS.override.md").contains("Hosts through the fleet."));
    assert_eq!(f.read("checkout/AGENTS.md"), "Tracked text.\n");
    let exclude = f.read("checkout/.git/info/exclude");
    assert_eq!(exclude.matches("CLAUDE.local.md").count(), 1);
    assert_eq!(exclude.matches("AGENTS.override.md").count(), 1);
    assert_eq!(
        git(&f.path("wt"), &["status", "--porcelain"]),
        "",
        "the files are ignored, the worktree stays clean"
    );

    // A public repo entry: the tracked file is now reported with the change, still not written.
    f.write("pub/stack.toml", "name = \"pub\"\nvisibility = \"public\"\n[repos.beta-core]\n");
    f.write(
        "pub/repo/beta-core/rules/r.md",
        &entry("rule.r", "repo:beta-core", "public", "", "Public repo rule.\n"),
    );
    let p = plan(&f.stacks(), &opts).unwrap();
    let tracked = p.items.iter().find(|i| i.target.contains("tracked AGENTS.md")).unwrap();
    assert_eq!(tracked.action, Action::Report);
    assert!(tracked.diff.contains("+Public repo rule."));
    apply(&p, &f.path("backups2")).unwrap();
    assert_eq!(f.read("checkout/AGENTS.md"), "Tracked text.\n");

    f.write("wt/CLAUDE.local.md", "tracked by someone\n");
    git(&f.path("wt"), &["add", "-f", "CLAUDE.local.md"]);
    let p = plan(&f.stacks(), &opts).unwrap();
    assert!(p.items.iter().any(|i| i.action == Action::Conflict));
    assert!(apply(&p, &f.path("backups3")).is_err());
}

