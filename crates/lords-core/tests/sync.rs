// Spec (Layers): composition takes the applicable entries, drops what an applicable entry overrides, orders by
// section (intent, roles, rules, facts, status) then layer; each output line maps back to its entry's file line.
#[test]
fn composition_orders_sections_and_applies_overrides() {
    let f = Fixture::new();
    f.write("pub/global/rules/a.md", &entry("rule.a", "global", "public", "", "Public rule.\n"));
    f.write(
        "pub/global/rules/z.md",
        &entry("rule.z", "global", "public", "", "Another public rule.\n"),
    );
    f.write(
        "priv/global/rules/b.md",
        &entry("rule.b", "global", "private", "overrides: [rule.z]\n", "Private rule.\n"),
    );
    f.write(
        "priv/global/intent/i.md",
        &entry("intent.i", "global", "private", "", "Exceed, not parity.\n"),
    );
    f.write(
        "pub/global/templates/t.md",
        &entry("template.t", "global", "public", "", "Not composed.\n"),
    );
    let c = compose(&f.stacks(), &global(vec![Audience::Opus]));
    assert_eq!(
        c.text,
        format!(
            "{BEGIN}\n<!-- Generated by Lords Command from its stacks; change an entry there, then sync. -->\n# Owner intent\n\nExceed, not parity.\n\n# Rules\n\nPublic rule.\n\nPrivate rule.\n{END}\n"
        )
    );
    assert_eq!(c.ids, ["intent.i", "rule.a", "rule.b"]);
    assert_eq!(c.overridden, ["rule.z"]);
    let line = c.text.lines().position(|l| l == "Private rule.").unwrap() + 1;
    let src = c.sources.iter().find(|s| s.line == line).unwrap();
    assert_eq!(
        (src.id.as_str(), src.file_line),
        ("rule.b", 13),
        "body starts after 12 frontmatter lines"
    );
    assert!(src.file.ends_with("priv/global/rules/b.md"));
}

// Spec (Layers, Sync: Sol and Astra share one file): an extension follows its entry; an entry for only part of
// a target's audience is labelled; an entry for none of it is left out.
#[test]
fn extensions_follow_and_partial_audiences_are_labelled() {
    let f = Fixture::new();
    f.write("pub/global/rules/a.md", &entry("rule.a", "global", "public", "", "Base.\n"));
    f.write(
        "priv/global/rules/c.md",
        &entry("rule.c", "global", "private", "extends: [rule.a]\n", "Detail.\n"),
    );
    f.write("pub/global/rules/b.md", &entry("rule.b", "global", "public", "", "Next.\n"));
    f.write(
        "priv/global/rules/s.md",
        &entry("rule.s", "global", "private", "", "Sol thing.\n").replace("[all]", "[sol]"),
    );
    f.write(
        "priv/global/rules/o.md",
        &entry("rule.o", "global", "private", "", "Opus thing.\n").replace("[all]", "[opus]"),
    );
    let c = compose(&f.stacks(), &global(vec![Audience::Sol, Audience::Astra]));
    let body: Vec<&str> = c.text.lines().skip(3).filter(|l| !l.is_empty() && *l != END).collect();
    assert_eq!(body, ["Base.", "Detail.", "Next.", "(Sol only)", "Sol thing."]);
}

