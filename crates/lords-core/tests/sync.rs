// Spec (Sync): the composed text goes between the markers and text outside them stays; `own_text = "replace"`
// makes the whole file the block; the plan only reads; apply backs up what it replaces; then it is in sync, and
// an edit inside the block shows as drift.
#[test]
fn instruction_targets_keep_owner_text_and_report_drift() {
    let f = Fixture::new();
    f.write("pub/global/rules/a.md", &entry("rule.a", "global", "public", "", "Rule A.\n"));
    let kept = f.write("home/keep/CLAUDE.md", "My own line.\n");
    let replaced = f.write("home/replace/AGENTS.md", "Old global text.\n");
    let missing = f.path("home/new/CLAUDE.md");
    with_targets(
        &f,
        &[
            target("keep", "claude", "instructions", &kept, ""),
            target("replace", "codex", "instructions", &replaced, "own_text = \"replace\"\n"),
            target("new", "claude", "instructions", &missing, ""),
        ]
        .concat(),
    );
    let s = f.stacks();
    let p = plan(&s, &Options { user_only: true, ..Options::default() }).unwrap();
    let actions: Vec<&Action> = p.items.iter().map(|i| &i.action).collect();
    assert_eq!(actions, [&Action::Update, &Action::Update, &Action::Create]);
    assert_eq!(f.read("home/keep/CLAUDE.md"), "My own line.\n", "planning only reads");
    assert!(p.items[0].diff.contains("+Rule A."));

    let backups = f.path("backups");
    apply(&p, &backups).unwrap();
    let k = f.read("home/keep/CLAUDE.md");
    assert!(
        k.starts_with("My own line.\n\n<!-- lords-command:begin -->")
            && k.contains("Rule A.")
            && k.ends_with(&format!("{END}\n"))
    );
    assert!(f.read("home/replace/AGENTS.md").starts_with(BEGIN));
    let saved: Vec<String> = fs::read_dir(&backups)
        .unwrap()
        .flatten()
        .map(|e| fs::read_to_string(e.path()).unwrap())
        .collect();
    assert_eq!(
        saved.len(),
        2,
        "each replaced file is backed up; the new one had nothing to back up"
    );
    assert!(saved.contains(&"Old global text.\n".to_string()));

    let p = plan(&f.stacks(), &Options { user_only: true, ..Options::default() }).unwrap();
    assert!(p.items.iter().all(|i| i.action == Action::InSync));
    fs::write(&kept, k.replace("Rule A.", "Rule A, edited by hand.")).unwrap();
    let p = plan(&f.stacks(), &Options { user_only: true, ..Options::default() }).unwrap();
    assert_eq!(p.items[0].action, Action::Update);
    assert!(p.items[0].diff.contains("-Rule A, edited by hand.\n+Rule A."));
}

